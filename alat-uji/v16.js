const { chromium } = require('playwright');
const fs = require('fs');
const FILE = process.env.FILE || 'file:///home/user/Sugimation/cuan-iklan.html';
const RAW = fs.readFileSync(__dirname + '/dl.html', 'utf8');
const out = [], errors = []; const ok = (n, c, x = '') => out.push(`${c ? 'PASS' : 'FAIL'}  ${n}${x ? '  — ' + x : ''}`);
(async () => {
  const b = await chromium.launch(); const page = await b.newPage({ viewport: { width: 390, height: 844 } });
  page.on('pageerror', e => errors.push(e.message));
  const sent = [];
  await page.route('**/*', r => {
    const u = r.request().url();
    if (u.startsWith('file:')) return r.continue();
    if (u.startsWith('https://raw.githubusercontent.com')) return r.fulfill({ status: 200, headers: { 'access-control-allow-origin': '*' }, contentType: 'text/plain', body: RAW });
    if (!u.includes('generativelanguage')) return r.abort();
    const body = JSON.parse(r.request().postData()); const sys = body.systemInstruction.parts[0].text, prompt = body.contents[0].parts[0].text;
    sent.push({ sys, prompt });
    let text = 'Hasil tiruan.';
    if (sys.includes('{"hook":')) text = JSON.stringify({ hook: [{ jenis: 'Hasil dulu', emoji: '🏆', kalimat: 'Sarung adem buat ke masjid', visual: 'Sarung dikibaskan.' }] });
    else if (sys.includes('"pertanyaan"')) text = JSON.stringify({ ringkasan: 'Iklan sarung.', pertanyaan: [] });
    else if (sys.includes('Auditor Quality Control')) text = '1. Sesuai cerita: Lolos - ok';
    else if (/Character Sheet Prompt/.test(sys)) text = 'Character reference sheet of the person from the reference photo, keeping their face exactly as in the photo, wearing a white koko shirt.';
    else if (/SCENE (\d+) OF/.test(prompt)) text = 'The person from the reference photo, wearing a black peci, unfolds the product. Narrator: "Sarung ini enak dipakai ke masjid." Avoid: music.';
    r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ candidates: [{ content: { parts: [{ text }] } }] }) });
  });
  await page.goto(FILE); await page.waitForFunction(() => document.querySelectorAll('#landing-themes button').length > 0);
  const click = async t => { await page.locator('#app-container button:visible', { hasText: t }).first().click(); await page.waitForTimeout(150); };
  await page.locator('#landing-themes button', { hasText: 'Review jujur saat dipakai' }).click();
  await click('Tulis ide sendiri');
  await page.fill('#story-field', 'Aku memakai sarung tenun ke masjid, adem dan rapi.'); await page.click('#btn-lanjut');
  await click('Lanjut'); await click('Lanjut');
  await page.locator('#app-container button').filter({ hasText: '8detik' }).first().click(); await page.waitForTimeout(150);
  await click('Lanjut'); await click('Lanjut');
  ok('kolom "Ciri yang tidak boleh berubah" tersembunyi sebelum foto dipilih', !(await page.locator('#f-ciriTetap').count()));
  await click('Pakai wajahku sendiri');
  ok('kolom ciri tetap + tips foto muncul', await page.locator('#f-ciriTetap').isVisible() && /Tips foto/.test(await page.locator('#app-container').innerText()));
  await page.fill('#f-ciriTetap', 'berpeci hitam, berkacamata');
  await click('Lanjut');
  await page.waitForSelector('text=Sarung adem buat ke masjid');
  await page.locator('#app-container button', { hasText: 'Sarung adem buat ke masjid' }).click();
  await page.locator('#app-container button', { hasText: /^Lanjut$/ }).click(); await page.waitForTimeout(150);
  await click('Multi referensi');
  const sum = await page.locator('#app-container').innerText();
  ok('ringkasan menampilkan ciri tetap', /Ciri tetap[\s\S]{0,20}berpeci hitam, berkacamata/.test(sum));
  await click('Sutradarai Videoku');
  await page.waitForFunction(() => !isProcessingQueue && /Hasil Prompt Videomu/.test(document.getElementById('app-container').innerText), null, { timeout: 30000 });
  const cs = sent.find(x => /Character Sheet Prompt/.test(x.sys));
  ok('Character Sheet: wajib mulai dari foto referensi', !!cs && cs.sys.includes('Character reference sheet of the person from the reference photo'));
  ok('ciri tetap dikirim ke AI', sent.some(x => x.prompt.includes('berpeci hitam, berkacamata') || x.sys.includes('berpeci hitam, berkacamata')));
  const res = await page.locator('#app-container').innerText();
  ok('panduan "Agar wajah konsisten" tampil', /Agar wajah konsisten/.test(res));
  const qcv = await page.inputValue('#res-qc'); ok('pemeriksaan otomatis: tidak ada temuan foto sendiri', !/Foto sendiri -|Character Sheet: Perlu/.test(qcv), (qcv.split('OTOMATIS')[1] || '').replace(/\n/g, ' | ').slice(0, 400));
  ok('tanpa error JavaScript', !errors.length, errors.join(' | '));
  await page.screenshot({ path: __dirname + '/v16-hasil.png' });
  await b.close(); console.log(out.join('\n'));
})();
